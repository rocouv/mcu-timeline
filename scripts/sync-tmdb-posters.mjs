import { readFile, writeFile } from 'node:fs/promises';

const token = process.env.TMDB_API_TOKEN;
if (!token) {
  console.error('Missing TMDB_API_TOKEN. Create one at https://www.themoviedb.org/settings/api');
  process.exit(1);
}

const data = await readFile(new URL('../src/data/marvel-content.ts', import.meta.url), 'utf8');
const entries = [...data.matchAll(/(?:movie|series)\('([^']+)', '([^']+)'/g)].map(([, id, title]) => ({ id, title }));
const posterPaths = {};
const manualTmdbIds = {
  'spider-man': 557,
  'spider-man-2': 558,
  'spider-man-3': 559,
  'x-men': 36657,
  'fantastic-four-2015': 166424,
  daredevil: 9480,
  punisher: 7220,
};

for (const entry of entries) {
  if (manualTmdbIds[entry.id]) {
    const response = await fetch(`https://api.themoviedb.org/3/movie/${manualTmdbIds[entry.id]}?language=es-MX`, {
      headers: { Authorization: `Bearer ${token}`, accept: 'application/json' },
    });
    if (response.ok) {
      const movie = await response.json();
      if (movie.poster_path) posterPaths[entry.id] = movie.poster_path;
      continue;
    }
  }
  const endpoint = entry.title.includes('Temporada') ? 'tv' : 'multi';
  const response = await fetch(`https://api.themoviedb.org/3/search/${endpoint}?language=es-MX&query=${encodeURIComponent(entry.title.replace(/ · Temporada \d+$/, ''))}`, {
    headers: { Authorization: `Bearer ${token}`, accept: 'application/json' },
  });
  if (!response.ok) {
    console.warn(`TMDB request failed for ${entry.title}: ${response.status}`);
    continue;
  }
  const results = (await response.json()).results ?? [];
  const match = results.find((item) => item.poster_path) ?? results[0];
  if (match?.poster_path) posterPaths[entry.id] = match.poster_path;
  else console.warn(`No poster found for ${entry.title}`);
}

const output = `// Generated by bun run sync:posters. Do not edit manually.\nexport const tmdbPosterPaths: Record<string, string> = ${JSON.stringify(posterPaths, null, 2)};\n`;
await writeFile(new URL('../src/data/tmdb-posters.ts', import.meta.url), output);
console.log(`Saved ${Object.keys(posterPaths).length} TMDB poster paths.`);
